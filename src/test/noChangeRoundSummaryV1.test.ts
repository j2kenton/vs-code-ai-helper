/**
 * bugs4 item 12: a round that changes no files must not remove content from the
 * task's current implementation summary. The captured failure alternated a full
 * before-and-after table with a short "nothing to change" report, and the score
 * followed (7, 9, 7, 9 ...).
 */
import * as assert from "node:assert/strict";
import { describe, it } from "node:test";

import {
  NO_CHANGE_ROUND_NOTE_MARKER_V1,
  buildUnusableImplementationSummaryV1,
  mergeNoChangeRoundIntoSummaryV1,
  parseReportedFilesChangedV1,
} from "../utils/implementationArtifactResolver";

const FULL_SUMMARY = [
  "<!-- Generated by Claude Code (claude-sonnet-5-5@high) -->",
  "",
  "## Files Changed",
  "- `src/copy.ts` — new wording.",
  "",
  "## Before and after",
  "",
  "| Before | After |",
  "| --- | --- |",
  "| all your data | your account details |",
  "",
  "## Verification",
  "- `pnpm run test:unit -- src/test/copy.test.ts` — 31 passed, 0 failed.",
].join("\n");

const noOpRound = (n: number): string =>
  [
    "<!-- Generated by Claude Code (claude-sonnet-5-5@high) -->",
    "<!-- ensemble:no-checklist-change -->",
    "",
    "## Files Changed",
    "- none",
    "",
    "## Verification",
    `Nothing to change (round ${n}).`,
  ].join("\n");

void describe("mergeNoChangeRoundIntoSummaryV1 (bugs4 item 12)", () => {
  void it("keeps the substantive summary, table included, and appends the round's note", () => {
    const merged = mergeNoChangeRoundIntoSummaryV1(FULL_SUMMARY, noOpRound(1));
    assert.ok(merged.startsWith(FULL_SUMMARY));
    assert.ok(merged.includes("| all your data | your account details |"));
    assert.ok(merged.includes("Nothing to change (round 1)."));
    assert.ok(merged.includes(NO_CHANGE_ROUND_NOTE_MARKER_V1));
  });

  void it("two consecutive no-change rounds leave the table and the substantive part identical, with one note", () => {
    const afterOne = mergeNoChangeRoundIntoSummaryV1(FULL_SUMMARY, noOpRound(1));
    const afterTwo = mergeNoChangeRoundIntoSummaryV1(afterOne, noOpRound(2));
    assert.ok(afterTwo.startsWith(FULL_SUMMARY));
    assert.ok(afterTwo.includes("| all your data | your account details |"));
    assert.equal(afterTwo.split(NO_CHANGE_ROUND_NOTE_MARKER_V1).length - 1, 1, "only one note section");
    assert.ok(afterTwo.includes("Nothing to change (round 2)."));
    assert.ok(!afterTwo.includes("Nothing to change (round 1)."), "the earlier note is replaced, not accumulated");
  });

  void it("the note cannot be read as the summary's own sections or as a checklist echo", () => {
    const merged = mergeNoChangeRoundIntoSummaryV1(FULL_SUMMARY, noOpRound(1));
    const tail = merged.slice(merged.indexOf(NO_CHANGE_ROUND_NOTE_MARKER_V1) + NO_CHANGE_ROUND_NOTE_MARKER_V1.length);
    assert.doesNotMatch(tail, /^#{1,6}\s/m, "headings in the note are demoted to bold lines");
    assert.doesNotMatch(tail, /ensemble:no-checklist-change/);
    // The round's own "- none" Files Changed entry must not become the summary's Files Changed.
    const parsed = parseReportedFilesChangedV1(merged);
    assert.ok(parsed?.paths.includes("src/copy.ts"));
  });

  void it("with no existing summary, or a blank one, the round's report is written as is", () => {
    assert.equal(mergeNoChangeRoundIntoSummaryV1(undefined, noOpRound(1)), noOpRound(1));
    assert.equal(mergeNoChangeRoundIntoSummaryV1("  \n", noOpRound(1)), noOpRound(1));
  });

  void it("an unusable-round stamp is not preserved", () => {
    const stamp = buildUnusableImplementationSummaryV1("the summary had no Verification section", "runs/001.md");
    assert.equal(mergeNoChangeRoundIntoSummaryV1(stamp, noOpRound(1)), noOpRound(1));
  });
});
